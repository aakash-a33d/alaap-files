"""Find surface features that predict a label better than they should.

    python -m alaap_ai.community_moderation.training.check_confounds \
        --data data/combined.v7.jsonl --category unsafe_medical_advice

A classifier learns the easiest thing that separates its classes. When one class
is generated by a language model and the other is not — or when the two are
generated from different briefs — incidental properties of the *form* line up with
the label, and form is easier to learn than meaning. The model takes the shortcut,
validation cannot see it because validation is drawn from the same generator, and
the failure only appears on text a real person wrote.

`unsafe_medical_advice` has done this four times:

    a1-v4  mentions psychiatric medication   -> P(unsafe) = 0.726
    a1-v5  second-person imperative          (all 400 hard negatives were
                                              first-person or questions)
    a1-v7  phrased as a question             -> P(unsafe) = 0.780 in generated data
    a1-v7  names a relative                  -> P(unsafe) = 0.984, 62 against 1

Each was fixed by adding examples of the *other* class in the same form, and each
fix introduced the next one, because the fix was written by hand and only ever
addressed the feature that had already failed. This script is the general form of
that lesson: run it before training and it will name the next shortcut instead of a
probe finding it two runs later.

The rule it encodes: **whenever positives are added in some form, negatives must be
added in that same form.** A feature that is near-perfectly predictive is not a
useful signal — it is a shortcut waiting to be learned.

Restricting to synthetic records with `--generated-only` is usually the right read.
Benchmark text dilutes the ratio and hides the problem: measured across the whole
corpus the relative-naming confound looked like P(unsafe)=0.232, which is harmless.
Measured within the generated slices it was 0.984.
"""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

# Surface features, deliberately shallow. Each is something a model can key on
# without understanding the message, which is exactly what makes it dangerous.
FEATURES: dict[str, re.Pattern] = {
    "question": re.compile(r"\?\s*$"),
    "starts imperative": re.compile(
        r"^\s*(stop|quit|don'?t|do not|throw|cut|taper|lower|skip|ignore|avoid"
        r"|try|ask|talk|bring|call|write|check|speak|mention|keep)\b", re.I),
    "first person": re.compile(r"^\s*(i|i'?m|i'?ve|my|mine)\b", re.I),
    "second person": re.compile(r"\byou(r|'?re|'?ve)?\b", re.I),
    # Two features, not one, because the possessive carries the whole meaning
    # and a single pattern reported a shortcut that did not exist.
    #
    # This was written for `unsafe_medical_advice`, where the confound is
    # "invoking a relative who recovered without it" — always *my* cousin. On
    # `self_harm_encouragement` the harmful move is the opposite person: "your
    # sister has said the same thing about you". Measured with the `my` pattern,
    # that category came back 0.0x — 0 positives out of 928 — and looked like a
    # corpus gap needing another generation round. 205 of 300 in the slice
    # written to fix it named a relative; none of them could match.
    #
    # A feature that cannot fire on one class reports a perfect shortcut every
    # time, which is indistinguishable from finding a real one.
    "names my relative": re.compile(
        r"\bmy (sister|brother|cousin|friend|mum|mom|dad|aunt|uncle|wife"
        r"|husband|partner|colleague|flatmate|neighbour|neighbor)\b", re.I),
    "names your relative": re.compile(
        r"\byour (sister|brother|cousin|friend|mum|mom|dad|aunt|uncle|wife"
        r"|husband|partner|family|parents|kids|son|daughter)\b", re.I),
    "names a dose": re.compile(r"\b\d+\s?mg\b", re.I),
    "names a clinician": re.compile(
        r"\b(psychiatrist|therapist|doctor|clinician|prescriber|gp|nurse)\b", re.I),
    "hedge": re.compile(r"\b(maybe|honestly|tbh|i guess|not telling you|if i were you)\b", re.I),
    # Typography, because the feature set was words and this confound is
    # punctuation — which is why it went unmeasured while reaching 14.6x lift on
    # `unsafe_medical_advice` and 9.6x on `passive_aggressive_abuse`, the two
    # categories built from generated text. A model will learn an apostrophe as
    # readily as a word, and this one separates the classes for free.
    "curly apostrophe": re.compile(r"[‘’]"),
    "curly quotes": re.compile(r"[“”]"),
    "em or en dash": re.compile(r"[–—]"),
}

# Measured as LIFT: how much more often a feature appears inside one class than
# the other, as a rate within each class.
#
#     lift = (matches in positives / positives) / (matches in benign / benign)
#
# This was originally P(label | feature) against a flat 0.85, which is only
# meaningful when the classes are balanced. They are not: `bullying_harassment`
# is 7,997 positive against 47,439 benign, so an entirely uninformative feature
# lands near the 0.14 base rate and every feature got flagged. Lift is
# base-rate independent and says the thing actually worth knowing — is this
# feature disproportionately in one class.
SUSPICIOUS_LIFT = 5.0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data", type=Path, required=True)
    parser.add_argument("--category", required=True)
    parser.add_argument("--generated-only", action="store_true", default=True,
                        help="restrict to gen-* ids (default; benchmark text hides "
                             "the ratio)")
    parser.add_argument("--all-records", dest="generated_only",
                        action="store_false")
    parser.add_argument("--min-support", type=int, default=15,
                        help="ignore features with fewer than this many matches")
    args = parser.parse_args()

    positives, negatives = [], []
    with args.data.open(encoding="utf-8") as fh:
        for line in fh:
            if not line.strip():
                continue
            record = json.loads(line)
            if args.generated_only and not record["id"].startswith("gen-"):
                continue
            if args.category in record["labels"]:
                positives.append(record["text"])
            elif not record["labels"]:
                negatives.append(record["text"])

    scope = "generated records only" if args.generated_only else "all records"
    print(f"\n  {args.data.name}: {args.category}")
    print(f"  {scope} — {len(positives)} positive, {len(negatives)} benign\n")
    if not positives or not negatives:
        print("  need both classes present to measure\n")
        return 1

    print(f"  {'feature':<22}{'in pos':>8}{'in neg':>8}{'lift':>9}")
    flagged = []
    for name, pattern in FEATURES.items():
        pos = sum(1 for t in positives if pattern.search(t))
        neg = sum(1 for t in negatives if pattern.search(t))
        if pos + neg < args.min_support:
            continue
        rate_pos = pos / len(positives)
        rate_neg = neg / len(negatives)
        # A feature absent from benign entirely would divide by zero; treat it as
        # if one benign record had it, which understates rather than inflates.
        lift = rate_pos / (rate_neg or 1 / len(negatives))

        mark = ""
        # The side to ADD is the under-represented one. A feature carried almost
        # only by positives is fixed by benign examples that carry it.
        if lift >= SUSPICIOUS_LIFT:
            flagged.append((name, lift, pos, neg, "benign"))
            mark = "  <- shortcut"
        elif lift <= 1 / SUSPICIOUS_LIFT:
            flagged.append((name, lift, pos, neg, "positive"))
            mark = "  <- shortcut"
        print(f"  {name:<22}{rate_pos:>7.1%}{rate_neg:>8.1%}{lift:>9.1f}{mark}")

    if flagged:
        print(f"\n  {len(flagged)} feature(s) are concentrated in one class:\n")
        for name, lift, pos, neg, side in flagged:
            direction = "positives" if lift >= SUSPICIOUS_LIFT else "benign"
            print(f"    {name!r}: {lift:.1f}x more common in {direction} "
                  f"({pos} positive / {neg} benign)")
            print(f"      Fix: add {side} examples that have this feature.\n")
        print("  Validation will not catch this when both classes come from the\n"
              "  same generator. Fix the corpus before training.\n")
        return 1

    print(f"\n  No surface feature is more than {SUSPICIOUS_LIFT:.0f}x "
          "concentrated in either class.\n"
          "  That rules out the shortcuts in this list, not shortcuts in general.\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
