"""Verify the Privacy Gateway's signature. The Python half of @alaap/service-auth.

WHY THIS EXISTS

Until now this tier answered anyone who could reach the port. That was defensible
while only a dev frontend called it, and stops being defensible the moment the
gateway routes to it: an unauthenticated classifier on the internal network is a
free oracle for testing what gets past moderation, and `/v1/moderate/internal`
returns the scores and thresholds that make that testing efficient.

So every `/v1/*` route now requires a signature only the gateway can produce.

THE CONTRACT, AND WHY IT IS RESTATED HERE RATHER THAN SHARED

There is no way to share code with the TypeScript implementation across the language
boundary, so this is a second implementation of one contract — exactly the situation
where two copies drift apart and nobody notices until requests start failing in
production. Three things keep them honest:

  1. The canonical form is defined by what is PRESENT, not by a fixed list of field
     names. That is what lets the gateway add a header without this file knowing about
     it. The TypeScript side learned this the hard way: it used to walk a fixed key
     list, and adding `x-alaap-device-id` broke every request to every service that
     had not been redeployed.
  2. `tests/test_service_auth.py` checks this implementation against signatures
     generated by the real Node signer, not against itself.
  3. Failures are logged with a reason and answered without one.

CANONICAL FORM

    every header whose name starts with `x-alaap-`, except the signature header
    lower-cased names, `name:value` per line, sorted, joined with "\\n"
    HMAC-SHA256 with the shared secret, base64url, no padding

WHAT IT DOES NOT PROTECT

The body. That is the caller's and this service validates it independently. What needs
integrity protection is the gateway's assertion about *who* is calling.

MVP MECHANISM. A shared secret distributed to many services is a weaker boundary than
the network segment it is meant to protect; mTLS replaces it before production. See
docs/adr and backend/gateway/src/routes/proxy.ts, which says the same thing.
"""

from __future__ import annotations

import base64
import hashlib
import hmac
import os
from dataclasses import dataclass
from datetime import datetime, timezone

SIGNATURE_HEADER = "x-alaap-service-auth"
HEADER_PREFIX = "x-alaap-"

# Five minutes. The signature carries no nonce, so a captured request is replayable
# within the window; bounding it is what keeps that from being indefinite. Matches
# MAX_CLOCK_SKEW_MS in the TypeScript implementation, and must keep matching.
MAX_CLOCK_SKEW_SECONDS = 300


@dataclass(frozen=True)
class VerifiedCaller:
    request_id: str
    actor_role: str
    purpose: str
    issued_at: datetime
    pseudo_id: int | None = None
    session_id: str | None = None


class SignatureError(Exception):
    """Refused. `reason` is for the log; the caller is told nothing but 401."""

    def __init__(self, reason: str) -> None:
        super().__init__(reason)
        self.reason = reason


def canonicalise(headers: dict[str, str]) -> str:
    """Every present x-alaap-* field, sorted, `name:value` per line.

    Driven by presence rather than a fixed list so a field added to the gateway later
    is covered automatically on both sides. Still strict in both directions: a header
    added, altered or removed in transit changes this string and breaks the signature.
    """
    lines = [
        f"{name.lower()}:{value}"
        for name, value in headers.items()
        if name.lower().startswith(HEADER_PREFIX)
        and name.lower() != SIGNATURE_HEADER
        and value is not None
    ]
    return "\n".join(sorted(lines))


def sign(headers: dict[str, str], secret: str) -> str:
    digest = hmac.new(
        secret.encode("utf-8"), canonicalise(headers).encode("utf-8"), hashlib.sha256
    ).digest()
    return base64.urlsafe_b64encode(digest).decode("ascii").rstrip("=")


def verify_request(
    headers: dict[str, str],
    secret: str,
    now: datetime | None = None,
) -> VerifiedCaller:
    """Raise SignatureError, or return who the gateway says is calling.

    Header names arrive case-insensitively from every ASGI server, so they are
    lower-cased before anything is compared or reconstructed.
    """
    lowered = {k.lower(): v for k, v in headers.items()}

    signature = lowered.get(SIGNATURE_HEADER)
    if signature is None:
        raise SignatureError("missing_signature")

    required = ("x-alaap-request-id", "x-alaap-actor-role", "x-alaap-purpose", "x-alaap-issued-at")
    if any(lowered.get(name) is None for name in required):
        raise SignatureError("missing_headers")

    # Signature before freshness: a caller must not be able to learn anything from the
    # difference between "wrongly signed" and "correctly signed but stale".
    expected = sign(lowered, secret)
    if not hmac.compare_digest(expected, signature):
        raise SignatureError("bad_signature")

    raw_issued = lowered["x-alaap-issued-at"]
    try:
        issued = datetime.fromisoformat(raw_issued.replace("Z", "+00:00"))
    except ValueError as exc:
        raise SignatureError("missing_headers") from exc
    if issued.tzinfo is None:
        issued = issued.replace(tzinfo=timezone.utc)

    drift = ((now or datetime.now(timezone.utc)) - issued).total_seconds()
    if drift > MAX_CLOCK_SKEW_SECONDS:
        raise SignatureError("stale_request")
    if drift < -MAX_CLOCK_SKEW_SECONDS:
        raise SignatureError("future_request")

    pseudo_id: int | None = None
    raw_pseudo = lowered.get("x-alaap-pseudo-id")
    if raw_pseudo is not None:
        try:
            pseudo_id = int(raw_pseudo)
        except ValueError:
            # Malformed rather than absent. Dropped rather than raised: the signature
            # already proved the gateway sent it, so this is a bug upstream, not an
            # attack, and refusing the whole request would be the wrong response.
            pseudo_id = None

    return VerifiedCaller(
        request_id=lowered["x-alaap-request-id"],
        actor_role=lowered["x-alaap-actor-role"],
        purpose=lowered["x-alaap-purpose"],
        issued_at=issued,
        pseudo_id=pseudo_id,
        session_id=lowered.get("x-alaap-session-id"),
    )


def secret_from_env() -> str | None:
    """The shared secret, or None when this tier is running unauthenticated.

    None is a legitimate configuration — `python ai-services/serve.py` on a laptop,
    with the dev frontend talking to it directly and no gateway in the picture. It is
    not a legitimate configuration anywhere a real person's words arrive, which is why
    the caller logs a warning rather than treating it as normal.
    """
    secret = os.getenv("ALAAP_SERVICE_AUTH_SECRET", "").strip()
    return secret or None
