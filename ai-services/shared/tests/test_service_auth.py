"""The Python verifier must agree with the real Node signer.

This is a second implementation of one contract across a language boundary, which is
exactly where two copies drift apart and nobody notices until requests fail in
production. So the fixtures below are not hand-written expectations — they are
signatures produced by `@alaap/service-auth` itself, regenerated by running:

    node ai-services/shared/tests/generate_service_auth_fixtures.mjs

A test that only checked this file against itself would pass happily while the two
sides disagreed, which is the failure it exists to prevent.
"""

from __future__ import annotations

import json
from datetime import datetime, timezone
from pathlib import Path

import pytest

from alaap_ai.shared.service_auth import (
    MAX_CLOCK_SKEW_SECONDS,
    SIGNATURE_HEADER,
    SignatureError,
    canonicalise,
    sign,
    verify_request,
)

_FIXTURES = Path(__file__).with_name("service_auth_fixtures.json")

pytestmark = pytest.mark.skipif(
    not _FIXTURES.exists(),
    reason="run generate_service_auth_fixtures.mjs to produce Node-signed fixtures",
)


def _load() -> dict:
    return json.loads(_FIXTURES.read_text(encoding="utf-8"))


def _at(iso: str) -> datetime:
    return datetime.fromisoformat(iso.replace("Z", "+00:00"))


def test_python_reproduces_every_node_signature() -> None:
    """The whole point. Same headers in, same signature out, on both sides."""
    data = _load()
    for case in data["cases"]:
        produced = sign(case["headers"], data["secret"])
        assert produced == case["signature"], case["name"]


def test_node_signed_requests_verify() -> None:
    data = _load()
    for case in data["cases"]:
        headers = {**case["headers"], SIGNATURE_HEADER: case["signature"]}
        caller = verify_request(headers, data["secret"], now=_at(case["headers"]["x-alaap-issued-at"]))
        assert caller.request_id == case["headers"]["x-alaap-request-id"]
        assert caller.actor_role == case["headers"]["x-alaap-actor-role"]


def test_a_field_this_version_has_never_heard_of_is_still_covered() -> None:
    """Forward compatibility, and the reason canonicalise is presence-driven.

    The TypeScript side learned this the hard way: it used to walk a fixed key list,
    and adding `x-alaap-device-id` broke every request to every service that had not
    been redeployed. A fixture containing an unknown field proves this copy does not
    have the same flaw.
    """
    data = _load()
    future = [c for c in data["cases"] if c["name"] == "unknown-future-field"]
    assert future, "fixture set must contain an unknown-field case"
    case = future[0]
    headers = {**case["headers"], SIGNATURE_HEADER: case["signature"]}
    assert verify_request(headers, data["secret"], now=_at(case["headers"]["x-alaap-issued-at"]))


@pytest.mark.parametrize("mutate", ["alter", "strip", "add"])
def test_tampering_with_any_signed_field_is_refused(mutate: str) -> None:
    """Forward compatibility must not become a hole."""
    data = _load()
    case = data["cases"][0]
    headers = {**case["headers"], SIGNATURE_HEADER: case["signature"]}

    if mutate == "alter":
        headers["x-alaap-actor-role"] = "admin"
    elif mutate == "strip":
        headers.pop("x-alaap-purpose")
    else:
        headers["x-alaap-injected"] = "by-an-attacker"

    with pytest.raises(SignatureError) as exc:
        verify_request(headers, data["secret"], now=_at(case["headers"]["x-alaap-issued-at"]))
    assert exc.value.reason in {"bad_signature", "missing_headers"}


def test_the_signature_header_is_not_itself_signed() -> None:
    """Otherwise signing would be circular and could never verify."""
    headers = {
        "x-alaap-request-id": "r1",
        "x-alaap-actor-role": "user",
        "x-alaap-purpose": "community-moderation",
        "x-alaap-issued-at": "2026-09-11T10:00:00.000Z",
    }
    assert canonicalise({**headers, SIGNATURE_HEADER: "anything"}) == canonicalise(headers)


def test_non_alaap_headers_are_ignored() -> None:
    """A proxy adding user-agent or x-forwarded-for must not break the signature."""
    headers = {
        "x-alaap-request-id": "r1",
        "x-alaap-actor-role": "user",
        "x-alaap-purpose": "community-moderation",
        "x-alaap-issued-at": "2026-09-11T10:00:00.000Z",
    }
    noisy = {**headers, "user-agent": "curl/8", "x-forwarded-for": "10.0.0.1"}
    assert canonicalise(noisy) == canonicalise(headers)


def test_header_case_does_not_matter() -> None:
    """ASGI servers normalise, but nothing in the contract may depend on that."""
    headers = {
        "X-Alaap-Request-Id": "r1",
        "x-alaap-actor-role": "user",
        "X-ALAAP-PURPOSE": "community-moderation",
        "x-alaap-issued-at": "2026-09-11T10:00:00.000Z",
    }
    secret = "s" * 40
    signature = sign(headers, secret)
    caller = verify_request(
        {**headers, SIGNATURE_HEADER: signature},
        secret,
        now=_at("2026-09-11T10:00:00.000Z"),
    )
    assert caller.purpose == "community-moderation"


def test_a_stale_request_is_refused() -> None:
    headers = {
        "x-alaap-request-id": "r1",
        "x-alaap-actor-role": "user",
        "x-alaap-purpose": "community-moderation",
        "x-alaap-issued-at": "2026-09-11T10:00:00.000Z",
    }
    secret = "s" * 40
    signed = {**headers, SIGNATURE_HEADER: sign(headers, secret)}

    late = _at("2026-09-11T10:00:00.000Z").timestamp() + MAX_CLOCK_SKEW_SECONDS + 1
    with pytest.raises(SignatureError) as exc:
        verify_request(signed, secret, now=datetime.fromtimestamp(late, tz=timezone.utc))
    assert exc.value.reason == "stale_request"


def test_a_request_from_the_future_is_refused() -> None:
    """A clock skewed the other way is just as unverifiable, and says so distinctly."""
    headers = {
        "x-alaap-request-id": "r1",
        "x-alaap-actor-role": "user",
        "x-alaap-purpose": "community-moderation",
        "x-alaap-issued-at": "2026-09-11T10:00:00.000Z",
    }
    secret = "s" * 40
    signed = {**headers, SIGNATURE_HEADER: sign(headers, secret)}

    early = _at("2026-09-11T10:00:00.000Z").timestamp() - MAX_CLOCK_SKEW_SECONDS - 1
    with pytest.raises(SignatureError) as exc:
        verify_request(signed, secret, now=datetime.fromtimestamp(early, tz=timezone.utc))
    assert exc.value.reason == "future_request"


def test_a_missing_signature_is_refused_before_anything_else() -> None:
    with pytest.raises(SignatureError) as exc:
        verify_request({"x-alaap-request-id": "r1"}, "s" * 40)
    assert exc.value.reason == "missing_signature"
